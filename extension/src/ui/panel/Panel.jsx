import { useCallback, useEffect, useRef, useState } from 'react';
import { FIRST_READ_TEXT, history, loadSettings, saveBrief, suggestQuestions } from '../../agent/agent.js';
import { renderOverview } from '../overview.js';
import { useListing } from '../hooks/useListing.js';
import { useBrief } from '../hooks/useBrief.js';
import { useAgentThread } from '../hooks/useAgentThread.js';
import AskForm from './components/AskForm.jsx';
import DomNode from './components/DomNode.jsx';
import Header from './components/Header.jsx';
import Setup from './components/Setup.jsx';
import Starters from './components/Starters.jsx';
import Thread from './components/Thread.jsx';

const DEFAULT_QUESTIONS = ['What will it cost me weekly?', 'What should I offer?', 'Is new supply a risk here?'];
const META = 'shrink-0 self-center font-mono text-[10px] text-muted';

/**
 * The panel: onboarding on first run; then an instant native overview of the listing
 * (built from the Microburbs brief, no model call) at the top of the thread, with
 * chat with the agent below it. Question chips are generated by the agent.
 */
export default function Panel() {
  const { listing, threadId, newThread } = useListing();
  const [settings, setSettings] = useState(null);
  const [showSetup, setShowSetup] = useState(false);
  const [briefVersion, setBriefVersion] = useState(0);
  const brief = useBrief(listing, briefVersion);
  const thread = useAgentThread();
  const { load, send, busy } = thread;
  const [questions, setQuestions] = useState(DEFAULT_QUESTIONS);
  const [questionsLoading, setQuestionsLoading] = useState(false);
  const qRun = useRef(0);

  useEffect(() => {
    loadSettings().then((s) => {
      setSettings(s);
      setShowSetup(!s.onboarded);
    });
  }, []);

  // load the transcript whenever the thread switches (no automatic agent read — the overview is instant)
  useEffect(() => {
    if (threadId) load(threadId);
  }, [threadId, load]);

  const loadedBrief = brief.status === 'ok' ? brief.res.brief : null;

  const refreshQuestions = useCallback(async () => {
    const my = ++qRun.current;
    setQuestionsLoading(true);
    const recent = threadId ? (await history(threadId).catch(() => [])).filter((m) => (m.role === 'user' && m.text !== FIRST_READ_TEXT) || m.role === 'agent') : [];
    const qs = await suggestQuestions({ brief: loadedBrief, recent });
    if (my !== qRun.current) return;
    setQuestionsLoading(false);
    if (qs?.length) setQuestions(qs);
  }, [threadId, loadedBrief]);

  // per-listing questions once the brief is in
  useEffect(() => {
    if (loadedBrief) refreshQuestions();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loadedBrief]);

  const ask = useCallback(
    async (text) => {
      await send(threadId, listing, text, loadedBrief);
      refreshQuestions(); // follow-ups for what was just said
    },
    [send, threadId, listing, loadedBrief, refreshQuestions],
  );

  const onSaveBrief = async (b) => {
    await saveBrief(b);
    const s = await loadSettings();
    setSettings(s);
    setShowSetup(false);
    setBriefVersion((v) => v + 1); // weekly cost etc. depend on the brief
  };

  // The panel's ✕ asks the host (content script) to close; only reply to our own origin.
  const onClose = () => {
    const parentOrigin = window.location.ancestorOrigins?.[0];
    if (parentOrigin) window.parent.postMessage({ type: 'fineprint:close' }, parentOrigin);
  };

  const overview = !listing ? null : brief.status === 'loading' || brief.status === 'idle' ? (
    <div className={`${META} meta-pulse`}>Reading this listing…</div>
  ) : brief.status === 'error' ? (
    <div className={META}>
      {brief.res.reason === 'no_match' ? `No exact match — ${brief.res.message}${brief.res.hint ? ` (${brief.res.hint})` : ''}` : brief.res.reason === 'no_address' ? brief.res.message : `Couldn't load Microburbs data — ${brief.res.message}`}
    </div>
  ) : (
    <DomNode
      className="overview"
      build={() => renderOverview(brief.res.brief, brief.investor ?? settings?.brief ?? {}, { onAsk: (q) => ask(q) })}
      deps={[brief.res, brief.investor]}
    />
  );

  return (
    <div className="flex h-screen flex-col">
      <Header brief={settings ? { ...settings.brief, onboarded: settings.onboarded } : null} onBrief={() => setShowSetup((v) => !v)} onNew={newThread} onClose={onClose} />
      {showSetup ? (
        <Setup brief={settings?.brief} onSave={onSaveBrief} />
      ) : (
        <>
          <Thread
            overview={overview}
            messages={thread.messages}
            liveText={thread.liveText}
            statusLine={thread.statusLine}
            eventLines={thread.eventLines}
            turnMeta={thread.turnMeta}
            turnError={thread.turnError}
          />
          <Starters busy={busy} questions={questions} loading={questionsLoading} onPick={ask} />
          <AskForm busy={busy} onSend={ask} />
        </>
      )}
    </div>
  );
}
